"""Write the FLEURS X->Y ST frozen-set specs, configs/fleurs24-st-x<tgt>-{dev,test}.yaml.

The X->en pair (fleurs24-st-xen-*.yaml) is hand-written and its header carries
the design notes; this generates the same design for other target languages:
every other EU-24 locale's FLEURS audio, scored against the target locale's
FLEURS `raw_transcription` of the same sentence id (configs/refs/
fleurs-<tgt>-reference-*.json, from scripts/build_fleurs_references.py). dev
keeps 100 utterances per source from `validation`, test all of `test`. The
ru/uk probes in the X->en specs are left out, so every X->Y set covers the
23 sources of the X->en set frozen before they were added (2026-09-15).

    python scripts/build_fleurs_st_configs.py de fr es it nl pt
"""

import argparse
from pathlib import Path

CONFIGS = Path(__file__).parent.parent / "configs"
# FLEURS locale per EU-24 language, in the X->en specs' order (en first here).
EU24 = {
    "en": "en_us", "es": "es_419", "fr": "fr_fr", "de": "de_de", "it": "it_it", "nl": "nl_nl",
    "pt": "pt_br", "pl": "pl_pl", "hu": "hu_hu", "fi": "fi_fi", "cs": "cs_cz", "ro": "ro_ro",
    "sv": "sv_se", "hr": "hr_hr", "sk": "sk_sk", "bg": "bg_bg", "lv": "lv_lv", "da": "da_dk",
    "lt": "lt_lt", "el": "el_gr", "et": "et_ee", "sl": "sl_si", "ga": "ga_ie", "mt": "mt_mt",
}
SPLITS = {"dev": ("validation", 100), "test": ("test", None)}


def render(tgt: str, split: str) -> str:
    """One spec: every EU-24 source but *tgt*, scored against *tgt*'s FLEURS text."""
    shar_split, max_samples = SPLITS[split]
    name = f"fleurs24-st-x{tgt}-{split}"
    lines = [
        f"# FLEURS X->{tgt} ST {split}: generated by scripts/build_fleurs_st_configs.py,",
        "# do not edit by hand. Same design as fleurs24-st-xen-test.yaml (see its",
        f"# header): the {EU24[tgt]} `raw_transcription` of each sentence id is the",
        f"# reference (configs/refs/fleurs-{tgt}-reference-{split}.json), one dataset_id",
        "# per source for per-direction BLEU/chrF, and ga has no source_text.",
        f"name: {name}",
        "seed: 0",
        "",
        "input_cfg:",
    ]
    for src, locale in EU24.items():
        if src == tgt:
            continue
        lines += [
            "  - type: lhotse_shar",
            f"    shar_path: ${{LOCAL_DATASETS_DIR}}/fleurs/{locale}/{shar_split}",
            "    source_text_field: custom.pnc_text",
            f"    reference_map: configs/refs/fleurs-{tgt}-reference-{split}.json",
        ]
        if max_samples is not None:
            lines.append(f"    max_samples: {max_samples}")
        lines += [
            f"    tags: {{task: st, src_lang: {src}, tgt_lang: {tgt}, dataset_id: fleurs-{src}_{tgt}}}",
            "",
        ]
    return "\n".join(lines).rstrip("\n") + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("targets", nargs="+", help="ISO codes of EU-24 target languages, not en")
    args = parser.parse_args()
    for tgt in args.targets:
        if tgt == "en" or tgt not in EU24:
            parser.error(f"{tgt!r}: pick a non-English EU-24 language (X->en is hand-written)")
        for split in SPLITS:
            path = CONFIGS / f"fleurs24-st-x{tgt}-{split}.yaml"
            path.write_text(render(tgt, split), encoding="utf-8")
            print(path)


if __name__ == "__main__":
    main()
